"""Какие вопросы канал уже задавал — восстановленная история.

19.11.2026 владелец: «что опросы что викторины никогда не должны повторяться и всегда
новые». Реестр заданных вопросов (`settings.poll_recent_keys`) бот ведёт с 16.11.2026
и до 19.11 терял значения при заливке на сервер, поэтому часть выходов в нём не
отмечена. Список ниже восстановлен по логам прогонов GitHub Actions (строки
«Опрос отправлен» / «Викторина отправлена») и подмешивается при чтении состояния:
вопрос из этого списка считается заданным навсегда.

Даты — фактический момент выхода в канал (UTC).
"""
from typing import Dict

LEGACY_ASKED: Dict[str, str] = {
    # опрос про наш бот
    "svc_usage": "2026-11-19 09:12:31",
    # викторина про контекстное окно
    "ai_context": "2026-11-18 15:09:35",
}


def merge_legacy(recent: Dict[str, str]) -> Dict[str, str]:
    """Дополнить реестр заданных вопросов восстановленной историей."""
    merged = dict(recent or {})
    for key, when in LEGACY_ASKED.items():
        merged.setdefault(key, when)
    return merged


__all__ = ["LEGACY_ASKED", "merge_legacy"]
